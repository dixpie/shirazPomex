async function seed() {
  await dbConnect();

  await Product.deleteMany({ slug: { $in: OLD_SLUGS } });
  await BlogPost.deleteMany({ slug: { $in: OLD_POST_SLUGS } });

  for (const p of products) {
    await Product.updateOne(
      { slug: slugify(p.title) },
      { $set: { ...p, slug: slugify(p.title) } },
      { upsert: true }
    );
  }

  for (const post of posts) {
    await BlogPost.updateOne(
      { slug: slugify(post.title) },
      { $set: { ...post, slug: slugify(post.title), author: "پومکس شیراز", published: true } },
      { upsert: true }
    );
  }

  console.log(`Seeded ${products.length} products and ${posts.length} blog posts.`);
  process.exit(0);
}

seed().catch((err) => {
  console.error(err);
  process.exit(1);
});
